import { randomUUID } from 'node:crypto';
import type { Row, Sql } from './index.ts';

/**
 * A durable job queue in the database, for work that must not be lost or done out of order, such
 * as two-way sync with connected apps. It runs on SQLite and on Postgres; on Postgres several
 * servers can take jobs from it at once (`for update skip locked`).
 *
 * - Jobs with the same `key` (say, one linked sheet) run one at a time, in the order they were
 *   queued. Jobs with different keys run side by side.
 * - A worker takes a job for a lease. If the worker dies, the job is taken again once the lease
 *   runs out; a worker whose lease ran out can't finish or fail it any more.
 * - A failed job is tried again later (waiting twice as long each time) until it has had
 *   `maxAttempts` tries; then it stays failed, with its last error, and the jobs behind it go on.
 * - A `dedupe` name keeps one waiting job per name: queuing it again while one waits does nothing.
 */

export type JobState = 'queued' | 'running' | 'done' | 'failed';

export interface QueuedJob<T = unknown> {
  id: string;
  queue: string;
  key: string;
  payload: T;
  state: JobState;
  attempts: number;
  maxAttempts: number;
  lastError: string | null;
}

export interface QueueOptions {
  /** Clock in milliseconds; tests pass their own. */
  now?: () => number;
  /** First wait after a failure; it doubles with each try. */
  retryBaseMs?: number;
  /** Longest wait between tries. */
  retryMaxMs?: number;
}

const table = (sql: Sql) => `
create table if not exists sync_jobs (
  id text primary key,
  queue text not null,
  key text not null,
  dedupe text,
  payload text not null,
  state text not null,
  attempts bigint not null default 0,
  max_attempts bigint not null,
  run_at bigint not null,
  locked_by text,
  locked_until bigint,
  last_error text,
  created_at bigint not null,
  updated_at bigint not null${sql.dialect === 'postgres' ? ',\n  rowid bigint generated by default as identity' : ''}
);
create index if not exists sync_jobs_due on sync_jobs (queue, state, run_at);
create index if not exists sync_jobs_by_key on sync_jobs (queue, key, state);
create unique index if not exists sync_jobs_dedupe on sync_jobs (queue, dedupe) where dedupe is not null and state = 'queued';
`;

const toJob = <T>(r: Row): QueuedJob<T> => ({
  id: String(r.id),
  queue: String(r.queue),
  key: String(r.key),
  payload: JSON.parse(String(r.payload)) as T,
  state: r.state as JobState,
  attempts: Number(r.attempts),
  maxAttempts: Number(r.max_attempts),
  lastError: r.last_error == null ? null : String(r.last_error),
});

export async function openQueue(sql: Sql, options: QueueOptions = {}) {
  const now = options.now ?? Date.now;
  const retryBaseMs = options.retryBaseMs ?? 5_000;
  const retryMaxMs = options.retryMaxMs ?? 15 * 60_000;
  // Several servers may open the queue at once; on Postgres two `create table if not exists`
  // can still collide, so they take turns.
  await sql.transaction(async (tx) => {
    if (tx.dialect === 'postgres')
      await tx.get(`select pg_advisory_xact_lock(hashtext('sync-jobs-schema'))`);
    await tx.exec(table(tx));
  });

  return {
    /** Adds a job. Returns its id, or null when a job with the same `dedupe` name already waits. */
    async enqueue<T>(
      queue: string,
      key: string,
      payload: T,
      opts: { dedupe?: string; delayMs?: number; maxAttempts?: number } = {},
    ): Promise<string | null> {
      const id = randomUUID();
      const t = now();
      const { changes } = await sql.run(
        `insert into sync_jobs (id, queue, key, dedupe, payload, state, attempts, max_attempts, run_at, created_at, updated_at)
         values (?, ?, ?, ?, ?, 'queued', 0, ?, ?, ?, ?)
         on conflict do nothing`,
        id,
        queue,
        key,
        opts.dedupe ?? null,
        JSON.stringify(payload),
        opts.maxAttempts ?? 8,
        t + (opts.delayMs ?? 0),
        t,
        t,
      );
      return changes ? id : null;
    },

    /**
     * Takes up to `limit` jobs that are due, for `leaseMs`: the oldest waiting job of each key
     * that has nothing earlier still waiting or running. Returns them, now running.
     */
    async claim<T>(queue: string, worker: string, leaseMs: number, limit = 1) {
      const t = now();
      return sql.transaction(async (tx) => {
        const rows = await tx.all(
          `select j.id from sync_jobs j
           where j.queue = ? and j.run_at <= ?
             and (j.state = 'queued' or (j.state = 'running' and j.locked_until <= ?))
             and not exists (
               select 1 from sync_jobs e
               where e.queue = j.queue and e.key = j.key and e.rowid < j.rowid
                 and e.state in ('queued', 'running')
             )
           order by j.run_at, j.rowid
           limit ?${tx.dialect === 'postgres' ? ' for update of j skip locked' : ''}`,
          queue,
          t,
          t,
          limit,
        );
        const taken: QueuedJob<T>[] = [];
        for (const { id } of rows) {
          const row = await tx.get(
            `update sync_jobs set state = 'running', locked_by = ?, locked_until = ?, updated_at = ?
             where id = ? and (state = 'queued' or (state = 'running' and locked_until <= ?))
             returning *`,
            worker,
            t + leaseMs,
            t,
            String(id),
            t,
          );
          if (row) taken.push(toJob<T>(row));
        }
        return taken;
      });
    },

    /** Marks a job done. False when this worker no longer holds it (its lease ran out). */
    async complete(id: string, worker: string) {
      const { changes } = await sql.run(
        `update sync_jobs set state = 'done', locked_by = null, locked_until = null, updated_at = ?
         where id = ? and state = 'running' and locked_by = ? and locked_until > ?`,
        now(),
        id,
        worker,
        now(),
      );
      return changes > 0;
    },

    /**
     * Records a failed try: the job waits and is tried again, or, after its last try, stays
     * failed. False when this worker no longer holds it.
     */
    async fail(id: string, worker: string, error: unknown) {
      const t = now();
      const message = (error instanceof Error ? error.message : String(error)).slice(0, 2000);
      return sql.transaction(async (tx) => {
        const row = await tx.get(
          `select queue, dedupe, attempts, max_attempts from sync_jobs
           where id = ? and state = 'running' and locked_by = ? and locked_until > ?`,
          id,
          worker,
          t,
        );
        if (!row) return false;
        const attempts = Number(row.attempts) + 1;
        // A newer job with the same dedupe name already waits and will do this work.
        const superseded =
          row.dedupe != null &&
          !!(await tx.get(
            `select 1 from sync_jobs where queue = ? and dedupe = ? and state = 'queued' and id <> ?`,
            row.queue,
            row.dedupe,
            id,
          ));
        if (superseded) {
          await tx.run(
            `update sync_jobs set state = 'done', attempts = ?, last_error = ?, locked_by = null,
               locked_until = null, updated_at = ? where id = ?`,
            attempts,
            `Superseded by a newer job after: ${message}`,
            t,
            id,
          );
          return true;
        }
        const last = attempts >= Number(row.max_attempts);
        const wait = Math.min(retryMaxMs, retryBaseMs * 2 ** (attempts - 1));
        await tx.run(
          `update sync_jobs set state = ?, attempts = ?, run_at = ?, last_error = ?,
             locked_by = null, locked_until = null, updated_at = ?
           where id = ?`,
          last ? 'failed' : 'queued',
          attempts,
          last ? t : t + wait,
          message,
          t,
          id,
        );
        return true;
      });
    },

    async job<T>(id: string) {
      const row = await sql.get('select * from sync_jobs where id = ?', id);
      return row ? toJob<T>(row) : null;
    },

    /** Jobs that ran out of tries, newest first, so they can be shown and looked into. */
    async failed<T>(queue: string, limit = 50) {
      const rows = await sql.all(
        `select * from sync_jobs where queue = ? and state = 'failed' order by updated_at desc limit ?`,
        queue,
        limit,
      );
      return rows.map((r) => toJob<T>(r));
    },

    /** Deletes finished jobs older than `ms`, keeping failed ones for a week longer. */
    async prune(ms: number) {
      const t = now();
      const { changes } = await sql.run(
        `delete from sync_jobs where (state = 'done' and updated_at < ?) or (state = 'failed' and updated_at < ?)`,
        t - ms,
        t - ms - 7 * 86_400_000,
      );
      return changes;
    },

    /**
     * Runs due jobs with `handle` until none are left. Each job is completed when `handle`
     * resolves and failed when it throws. Returns how many jobs ran.
     */
    async drain<T>(
      queue: string,
      worker: string,
      handle: (job: QueuedJob<T>) => Promise<void>,
      opts: { leaseMs?: number; concurrency?: number } = {},
    ) {
      let ran = 0;
      for (;;) {
        const jobs = await this.claim<T>(
          queue,
          worker,
          opts.leaseMs ?? 60_000,
          opts.concurrency ?? 4,
        );
        if (!jobs.length) return ran;
        await Promise.all(
          jobs.map(async (job) => {
            try {
              await handle(job);
              await this.complete(job.id, worker);
            } catch (error) {
              await this.fail(job.id, worker, error);
            }
            ran++;
          }),
        );
      }
    },
  };
}

export type Queue = Awaited<ReturnType<typeof openQueue>>;
