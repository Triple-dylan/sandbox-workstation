/**
 * The Postgres schema, kept in step with the SQLite one in `server/db.ts`. `tests/sql.test.ts`
 * fails when a table or column exists there and not here, so add both together.
 *
 * Changing it:
 * - A new table goes in `postgresSchema` (`create table if not exists`).
 * - A new column on an existing table goes in `postgresMigrations` as
 *   `alter table … add column if not exists …`, because a database made earlier keeps its tables.
 * - Types: SQLite `integer` is `bigint` here (times in milliseconds outgrow 32 bits), `blob` is
 *   `bytea`. True/false stays a 0/1 integer, as in SQLite.
 * - Every table has a `rowid` identity column, because queries order by SQLite's `rowid` to keep
 *   rows in the order they were made. It sits after the original columns, so inserts written
 *   against Postgres name their columns rather than relying on position.
 */

